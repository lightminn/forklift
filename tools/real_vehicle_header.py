#!/usr/bin/env python3
"""Generate the firmware's vehicle header from config/real/vehicle.yaml (sim-to-real plan P0-6).

The header is a build product: the board build runs this tool, nothing writes the values by hand.
Counts per wheel revolution stay fractional on the host; the firmware's ``wheel_enc`` takes a
uint32, so they are rounded here with the error stated. The calibration ID is the one the host's
``RealVehicleConfig`` carries, so a firmware build and a host config can be matched.

usage: real_vehicle_header.py --config config/real/vehicle.yaml --out build/vehicle_config.h
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from forklift_core.plant.real_vehicle import (
    RealVehicleConfig,
    chassis_model_path,
    load_real_vehicle,
)

ROUNDING_LIMIT = 1e-5  # relative; a scale this coarse is a wrong configuration, not a rounding


def _counts(value: float, side: str) -> tuple[int, float]:
    rounded = round(value)
    if not 1 <= rounded <= 2**32 - 1:
        raise ValueError(f"counts per wheel revolution ({side}) {value} do not fit a uint32")
    error = abs(rounded - value) / value
    if error > ROUNDING_LIMIT:
        raise ValueError(f"counts per wheel revolution ({side}) {value} round to {rounded}: {error:.2e} relative")
    return rounded, error


def _float(value: float) -> str:
    text = repr(float(value))
    return (text if "." in text or "e" in text else text + ".0") + "f"


def render_header(cfg: RealVehicleConfig) -> str:
    lines = [
        "/* Generated by tools/real_vehicle_header.py from config/real/vehicle.yaml -- do not edit. */",
        "#ifndef FW_VEHICLE_CONFIG_H",
        "#define FW_VEHICLE_CONFIG_H",
        "",
        "/* Provenance (measured: false values wait for the bring-up step named in until):",
    ]
    for key in sorted(cfg.provenance):
        p = cfg.provenance[key]
        lines.append(f"   {key}: {p['source']}, measured: {str(p['measured']).lower()}, until: {p['until']}")
    lines += ["*/", ""]
    lines.append(f'#define FW_VEHICLE_CALIBRATION_ID "{cfg.calibration_id}"')
    lines.append(f"#define FW_VEHICLE_CALIBRATION_ID_U32 0x{cfg.calibration_id[:8]}u")
    for side, value, tag in zip(("left", "right"), cfg.counts_per_wheel_rev, ("L", "R"), strict=True):
        rounded, error = _counts(value, side)
        lines.append(f"/* {side}: host {value!r} counts/wheel rev, rounded by {error * 1e6:.2f} ppm */")
        lines.append(f"#define FW_WHEEL_COUNTS_PER_REV_{tag} {rounded}u")
    lines.append(f"#define FW_MAX_WHEEL_RAD_S {_float(cfg.wheel_rate_limit_rad_s)}")
    lines.append(f"/* Steering mechanism angle range ({cfg.steering.kind} map), the MCU's min/max_joint */")
    lines.append(f"#define FW_STEER_MIN_RAD {_float(cfg.steering.angle_range[0])}")
    lines.append(f"#define FW_STEER_MAX_RAD {_float(cfg.steering.angle_range[1])}")
    lines += ["", "#endif", ""]
    return "\n".join(lines)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--config", type=Path, required=True)
    ap.add_argument("--out", type=Path)
    ap.add_argument("--print-chassis", action="store_true",
                    help="print the chassis model file the config names (a build dependency) and exit")
    args = ap.parse_args(argv)
    if args.print_chassis:
        print(chassis_model_path(args.config))
        return 0
    if args.out is None:
        ap.error("--out is required")
    try:
        text = render_header(load_real_vehicle(args.config))
    except ValueError as exc:
        print(f"real_vehicle_header: {exc}", file=sys.stderr)
        return 2
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
