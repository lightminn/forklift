static int feed_all(link_rx *rx, const uint8_t *wire, size_t len, link_msg *last)
{
    int count = 0;
    for (size_t i = 0; i < len; i++) {
        if (link_rx_feed(rx, wire[i], last)) {
            count++;
        }
    }
    return count;
}

int main(void)
{
    link_rx rx;
    link_rx_init(&rx);
    link_msg m;
    CHECK_EQ_I(feed_all(&rx, BENCH_SET_000B, sizeof BENCH_SET_000B, &m), 0);
    CHECK_EQ_I(feed_all(&rx, BENCH_ARM_000C, sizeof BENCH_ARM_000C, &m), 0);
    CHECK_EQ_I(feed_all(&rx, BENCH_STATE_0103, sizeof BENCH_STATE_0103, &m), 0);
    CHECK_EQ_U(rx.errors, 3);
    link_msg out = {.type = LINK_BENCH_ARM, .seq = 1};
    uint8_t wire[LINK_WIRE_MAX];
    CHECK_EQ_U(link_encode(&out, wire, sizeof wire), 0); /* nor encoded */
    return fw_test_failures;
}
